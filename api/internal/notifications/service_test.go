func TestNotifyOtherMembersExcludesActorContinuesAfterFailureAndDeletesExpiredSubscription(t *testing.T) {
	t.Parallel()

	ctx := context.Background()
	db := newPostgresTestDatabase(t, ctx)

	requests := 0
	pushServer := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		requests++
		if r.URL.Path == "/expired" {
			http.Error(w, http.StatusText(http.StatusGone), http.StatusGone)
			return
		}
		w.WriteHeader(http.StatusCreated)
	}))
	t.Cleanup(pushServer.Close)

	store := NewStore(db)
	for memberID, endpoint := range []string{pushServer.URL + "/expired", pushServer.URL + "/current", pushServer.URL + "/actor"} {
		err := store.StoreSubscription(ctx, StoreSubscriptionParams{
			HouseholdId: 1,
			MemberId:    int64(memberID + 1),
			Endpoint:    endpoint,
			P256dh:      testP256dh,
			Auth:        testAuth,
		})
		if err != nil {
			t.Fatal(err)
		}
	}

	privateKey, publicKey, err := webpush.GenerateVAPIDKeys()
	if err != nil {
		t.Fatal(err)
	}
	service := NewNotificationService(db, publicKey, privateKey)

	err = service.NotifyOtherMembers(ctx, 1, 3, Notification{Title: "Test", Body: "Test"})
	if err == nil || !strings.Contains(err.Error(), "410 Gone") {
		t.Fatalf("expected a 410 delivery error, got %v", err)
	}
	if requests != 2 {
		t.Fatalf("expected both subscriptions to be attempted, got %d requests", requests)
	}

	subscriptions, err := store.GetSubscriptionsByHousehold(ctx, 1)
	if err != nil {
		t.Fatal(err)
	}
	if len(subscriptions) != 2 {
		t.Fatalf("expected the current and actor subscriptions to remain, got %#v", subscriptions)
	}
	for _, subscription := range subscriptions {
		if subscription.Endpoint == pushServer.URL+"/expired" {
			t.Fatalf("expired subscription was not deleted: %#v", subscriptions)
		}
	}
}

func TestStoreSubscriptionUpdatesExistingEndpoint(t *testing.T) {
	t.Parallel()

	ctx := context.Background()
	db := newPostgresTestDatabase(t, ctx)

	store := NewStore(db)
	first := StoreSubscriptionParams{HouseholdId: 1, MemberId: 1, Endpoint: "https://push.example.test/one", P256dh: "old", Auth: "old"}
	if err := store.StoreSubscription(ctx, first); err != nil {
		t.Fatal(err)
	}
	updated := StoreSubscriptionParams{HouseholdId: 1, MemberId: 2, Endpoint: first.Endpoint, P256dh: "new", Auth: "new"}
	if err := store.StoreSubscription(ctx, updated); err != nil {
		t.Fatal(err)
	}

	subscriptions, err := store.GetSubscriptionsByHousehold(ctx, 1)
	if err != nil {
		t.Fatal(err)
	}
	if len(subscriptions) != 1 {
		t.Fatalf("expected one subscription, got %d", len(subscriptions))
	}
	if subscriptions[0].MemberID != 2 || subscriptions[0].P256dh != "new" || subscriptions[0].Auth != "new" {
		t.Fatalf("subscription was not updated: %#v", subscriptions[0])
	}
}

func newPostgresTestDatabase(t *testing.T, ctx context.Context) *database.Database {
	t.Helper()

	databaseURL := os.Getenv("TEST_DATABASE_URL")
	if databaseURL == "" {
		t.Skip("TEST_DATABASE_URL is not set")
	}

	adminDB, err := sql.Open("postgres", databaseURL)
	if err != nil {
		t.Fatalf("open PostgreSQL test database: %v", err)
	}

	pingCtx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	if err := adminDB.PingContext(pingCtx); err != nil {
		adminDB.Close()
		t.Fatalf("connect to PostgreSQL test database: %v", err)
	}

	schema := fmt.Sprintf("notifications_test_%d", time.Now().UnixNano())
	quotedSchema := pq.QuoteIdentifier(schema)
	if _, err := adminDB.ExecContext(ctx, "CREATE SCHEMA "+quotedSchema); err != nil {
		adminDB.Close()
		t.Fatalf("create PostgreSQL test schema: %v", err)
	}

	schemaURL, err := databaseURLWithSearchPath(databaseURL, schema)
	if err != nil {
		_, _ = adminDB.ExecContext(ctx, "DROP SCHEMA "+quotedSchema+" CASCADE")
		adminDB.Close()
		t.Fatalf("set PostgreSQL test search path: %v", err)
	}

	db, err := database.New(ctx, schemaURL)
	if err != nil {
		_, _ = adminDB.ExecContext(ctx, "DROP SCHEMA "+quotedSchema+" CASCADE")
		adminDB.Close()
		t.Fatalf("open isolated PostgreSQL test database: %v", err)
	}

	t.Cleanup(func() {
		if err := db.Close(); err != nil {
			t.Errorf("close PostgreSQL test database: %v", err)
		}
		if _, err := adminDB.ExecContext(context.Background(), "DROP SCHEMA "+quotedSchema+" CASCADE"); err != nil {
			t.Errorf("drop PostgreSQL test schema: %v", err)
		}
		if err := adminDB.Close(); err != nil {
			t.Errorf("close PostgreSQL admin connection: %v", err)
		}
	})

	_, err = db.ExecContext(ctx, `
		CREATE TABLE push_subscriptions (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			household_id BIGINT NOT NULL,
			member_id BIGINT NOT NULL,
			endpoint TEXT NOT NULL UNIQUE,
			p256dh TEXT NOT NULL,
			auth TEXT NOT NULL,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		)
	`)
	if err != nil {
		t.Fatalf("create push_subscriptions test table: %v", err)
	}

	return db
}

func databaseURLWithSearchPath(databaseURL, schema string) (string, error) {
	parsedURL, err := url.Parse(databaseURL)
	if err != nil {
		return "", fmt.Errorf("parse database URL: %w", err)
	}

	query := parsedURL.Query()
	query.Set("search_path", schema)
	parsedURL.RawQuery = query.Encode()
	return parsedURL.String(), nil
}
